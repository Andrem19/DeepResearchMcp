class JobStatus(StrEnum):
    """Status of a research job."""

    PENDING = "pending"
    RUNNING = "running"
    COMPLETED = "completed"
    FAILED = "failed"
    EXPIRED = "expired"


class ResearchJob(BaseModel):
    """A background research job."""

    job_id: str = Field(min_length=1, description="Unique job identifier")
    query: str = Field(min_length=1)
    depth: str = "standard"
    max_sources: int = 8
    recency_days: int | None = None
    status: JobStatus = JobStatus.PENDING
    created_at: datetime = Field(default_factory=_utc_now)
    started_at: datetime | None = None
    completed_at: datetime | None = None
    report_markdown: str | None = None
    error_message: str | None = None
    source_count: int = 0
    research_duration_seconds: float = 0.0

    @property
    def is_terminal(self) -> bool:
        """Whether the job has reached a terminal state."""
        return self.status in (JobStatus.COMPLETED, JobStatus.FAILED, JobStatus.EXPIRED)
